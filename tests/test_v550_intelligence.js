const assert=require('node:assert/strict');
const v=require('../frontend/address-intelligence-v550.js');
const aliases=['Cra 25 18C 86','Carrera 25 número 18C-86','Kr 25 #18C-86'];
for(const a of aliases)assert.equal(v.key(a),'carrera|25|18c|86',a);
assert.equal(v.key('Calle 14 #26-86'),'calle|14|26|86');
assert.notEqual(v.key('Calle 14 #26-86'),v.key('Calle 16B #26-86'));
assert.equal(v.parts('Calle 14 #26-86').main,'14');
assert.equal(v.parts('Calle 14 #26-86').cross,'26');
assert.equal(v.parts('Calle 14 #26-86').door,'86');
assert.equal(v.parts('Calle 14 con Carrera 26').complete,false);
assert.equal(v.findConfirmed('Calle 14 #26-86',[{address:'Calle 14 #26-86',lat:11,lng:-74.2,source:'osm'}]),null);
const confirmed={address:'CL 14 26 86',lat:11,lng:-74.2,source:'gps-confirmado',verifiedAt:'2026-11-13'};
assert.equal(v.findConfirmed('Calle 14 #26-86',[confirmed]).lat,11);
assert.equal(v.findConfirmed('Calle 14 #26-87',[confirmed]),null);
const entries=[{id:'a',status:'entregado'},{id:'b',status:'pendiente'},{id:'c',status:'pendiente'}];
assert.equal(v.relativeNumber(entries[1],entries),1);
assert.equal(v.relativeNumber(entries[2],entries),2);
assert.equal(v.relativeNumber(entries[0],entries),null);
assert.equal(v.status({lat:11,lng:-74.2,locationStatus:'estimada'}),'aproximada');
console.log('V5.5.0: alias equivalentes, calle principal, memoria confirmada, estados y numeracion: OK');
